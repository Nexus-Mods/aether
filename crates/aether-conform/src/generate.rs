//! `aether-conform run --generate`: generated cases, each played against the
//! director under test and compared with the reference.
//!
//! A case is a tree and a sequence of operations ([`crate::model`]). For
//! each one, the generator reads the operations against an in-process
//! reference serving the tree, which gives every step its expectation (the
//! reference's answer, or a `one_of` where wire.md allows several); the
//! case is then an ordinary [`Scenario`], written to a scratch file, mounted
//! through the adapter and played as a scenario is ([`crate::run`]), so the
//! comparison is [`crate::compare::Session`]'s with all its rules.
//!
//! Cases come from proptest strategies driven by one seed (ChaCha, the
//! 32-byte seed spread from the `u64` one), so `--seed` replays a run. The
//! first case that fails is shrunk the way proptest shrinks (simplify while
//! it still fails, complicate when it passes), each candidate played
//! against the director, then op by op (each template taken apart, and ops
//! dropped one at a time while it still fails); the smallest failing one is
//! written to the failures folder as a scenario file, which `run
//! --scenarios` replays.
//!
//! `proptest-state-machine` is not used: its reference state machine wants
//! a model of the answers, which here is the reference director itself, and
//! its shrinking would run the system under test in-process. A plain
//! strategy for (tree, operations) whose operations pick their targets
//! against the oracle's state as they are read ([`crate::model::build`])
//! keeps every shrunk case valid and plays each through the adapter's own
//! mount.

use std::path::{Path, PathBuf};
use std::time::Duration;

use proptest::strategy::{Strategy, ValueTree};
use proptest::test_runner::{Config, RngAlgorithm, TestRng, TestRunner};

use crate::adapter::{Adapter, AdapterError};
use crate::model::{self, CaseInput, Limits};
use crate::run::{play_file, ScenarioResult};
use crate::scenario::{to_json_string, Scenario};

/// Cases a run plays when `--cases` is not given.
pub const DEFAULT_CASES: u32 = 64;
/// The most operations a case has (`--steps`).
pub const DEFAULT_STEPS: usize = 32;
/// The most shrinking candidates played for one failure.
const MAX_SHRINK_ITERS: u32 = 2048;

/// What a generated run does.
#[derive(Debug, Clone)]
pub struct GenerateOptions {
    pub cases: u32,
    pub seed: u64,
    /// The most operations per case.
    pub steps: usize,
    /// Where the shrunk failing case is written.
    pub failures: PathBuf,
}

/// Why a generated run stopped before it was done.
#[derive(Debug)]
pub enum GenerateError {
    /// The adapter failed; the run ends as for scenarios.
    Adapter(AdapterError),
    /// The reference answered a generated request otherwise than wire.md
    /// says, so the generator has no expectation to give it; or a case file
    /// could not be written.
    Generator(String),
}

impl From<AdapterError> for GenerateError {
    fn from(e: AdapterError) -> GenerateError {
        GenerateError::Adapter(e)
    }
}

/// The test runner, used only as the source of randomness, for `seed`.
pub(crate) fn runner(seed: u64) -> TestRunner {
    let mut bytes = [0u8; 32];
    for (i, chunk) in bytes.chunks_mut(8).enumerate() {
        let word = seed ^ (i as u64).wrapping_mul(0x9E37_79B9_7F4A_7C15);
        chunk.copy_from_slice(&word.to_le_bytes());
    }
    let config = Config {
        failure_persistence: None,
        ..Config::default()
    };
    TestRunner::new_with_rng(config, TestRng::from_seed(RngAlgorithm::ChaCha, &bytes))
}

/// Case `case` of the run with `seed`, as a scenario.
fn scenario_for(
    seed: u64,
    case: u32,
    input: &CaseInput,
    limits: Limits,
) -> Result<Scenario, String> {
    let name = format!("generated-{seed}-{case}");
    let description = format!(
        "Generated by `aether-conform run --generate --seed {seed}`, case {case} (shrunk if it \
         failed): a tree and operations on it, each step expecting the reference's answer, or \
         the answers wire.md allows (docs/conformance.md, \"Generated cases\")."
    );
    model::build_with(input, &name, &description, limits)
}

/// The first `n` cases of the run with `seed`, at most `steps` operations
/// each, as scenarios: what a run plays, in order, until one fails.
pub fn cases(seed: u64, n: u32, steps: usize) -> Result<Vec<Scenario>, String> {
    let mut runner = runner(seed);
    let strategy = model::case_strategy(steps);
    (0..n)
        .map(|i| {
            let tree = strategy.new_tree(&mut runner).map_err(|e| e.to_string())?;
            scenario_for(seed, i, &tree.current(), Limits::default())
        })
        .collect()
}

/// A folder of its own for the case files a run mounts.
pub(crate) fn scratch() -> Result<PathBuf, GenerateError> {
    let t = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    let dir = std::env::temp_dir().join(format!(
        "aether-conform-generate-{}-{t}",
        std::process::id()
    ));
    std::fs::create_dir_all(&dir).map_err(|e| {
        GenerateError::Generator(format!("cannot create the folder {}: {e}", dir.display()))
    })?;
    Ok(dir)
}

/// Plays `opts.cases` generated cases against the adapter's director. The
/// result is one scenario named `generated`: passed, or the shrunk failing
/// case with its steps and the file it was written to.
pub fn run(
    adapter: &mut Adapter,
    opts: &GenerateOptions,
    timeout: Duration,
) -> Result<ScenarioResult, GenerateError> {
    let work = scratch()?;
    let outcome = cases_against(adapter, opts, timeout, &work.join("case.json"));
    let _ = std::fs::remove_dir_all(&work);
    outcome
}

/// The limits of the director's ring ([`Limits`]), from the environment
/// of a mount of an empty tree; the defaults if that mount is refused (every
/// case's mount will be too, and fail).
fn probe(adapter: &mut Adapter, file: &Path) -> Result<Limits, GenerateError> {
    let s = Scenario {
        name: "probe".into(),
        description: "An empty root, to learn the ring's payload cap and arena".into(),
        tree: crate::tree::Tree {
            roots: vec![crate::tree::Root::default()],
            registry: None,
        },
        steps: Vec::new(),
    };
    std::fs::write(file, to_json_string(&s))
        .map_err(|e| GenerateError::Generator(format!("cannot write {}: {e}", file.display())))?;
    match adapter.mount(file)? {
        Ok(env) => {
            adapter.unmount()?;
            let (cap, arena) = crate::attach::payload_cap_and_arena(&env);
            Ok(Limits {
                layers: adapter.serves_layers(),
                ..Limits::of(cap, arena)
            })
        }
        Err(_) => Ok(Limits::default()),
    }
}

/// How a case failed, for shrinking: a mismatch at a step of one opcode (the
/// first failing step's), or an error outside the steps, by its kind (the
/// text before its first `:`). A shrinking candidate counts only if it fails
/// the same way, so shrinking cannot wander to another failure.
fn failure_class(r: &ScenarioResult) -> Option<String> {
    if let Some(st) = r.steps.iter().find(|st| !st.passed) {
        let op = st.request["op"].as_str().unwrap_or("");
        return Some(format!("mismatch at {op}"));
    }
    r.error
        .as_deref()
        .map(|e| format!("error: {}", e.split(':').next().unwrap_or(e).trim()))
}

fn write_failure(opts: &GenerateOptions, s: &Scenario) -> Result<PathBuf, GenerateError> {
    std::fs::create_dir_all(&opts.failures).map_err(|e| {
        GenerateError::Generator(format!(
            "cannot create the folder {}: {e}",
            opts.failures.display()
        ))
    })?;
    let out = opts.failures.join(format!("{}.json", s.name));
    std::fs::write(&out, to_json_string(s))
        .map_err(|e| GenerateError::Generator(format!("cannot write {}: {e}", out.display())))?;
    Ok(out)
}

fn cases_against(
    adapter: &mut Adapter,
    opts: &GenerateOptions,
    timeout: Duration,
    file: &Path,
) -> Result<ScenarioResult, GenerateError> {
    let limits = probe(adapter, file)?;
    let mut runner = runner(opts.seed);
    let strategy = model::case_strategy(opts.steps);
    let mut play = |s: &Scenario| -> Result<ScenarioResult, GenerateError> {
        std::fs::write(file, to_json_string(s)).map_err(|e| {
            GenerateError::Generator(format!("cannot write {}: {e}", file.display()))
        })?;
        Ok(play_file(adapter, file, s, timeout)?)
    };
    let build = |case: u32, input: &CaseInput| {
        scenario_for(opts.seed, case, input, limits).map_err(GenerateError::Generator)
    };
    for case in 0..opts.cases {
        let mut tree = strategy
            .new_tree(&mut runner)
            .map_err(|e| GenerateError::Generator(e.to_string()))?;
        let s = build(case, &tree.current())?;
        let r = play(&s)?;
        if r.passed {
            continue;
        }
        // Shrink: simplify while it still fails the same way, complicate
        // when it passes or fails otherwise.
        let class = failure_class(&r);
        let mut best = (s, r);
        let mut best_input = tree.current();
        let mut iters = 0;
        let mut stopped = None;
        if tree.simplify() {
            while iters < MAX_SHRINK_ITERS {
                iters += 1;
                let input = tree.current();
                let tried = build(case, &input).and_then(|s| play(&s).map(|r| (s, r)));
                let (s, r) = match tried {
                    Ok(t) => t,
                    Err(e) => {
                        stopped = Some(e);
                        break;
                    }
                };
                if !r.passed && failure_class(&r) == class {
                    best = (s, r);
                    best_input = input;
                    if !tree.simplify() {
                        break;
                    }
                } else if !tree.complicate() {
                    break;
                }
            }
        }
        // Then op by op: each template taken apart into its ops, and each op
        // and the other clients dropped while the case still fails the same
        // way, which proptest's shrinking of a template as one op cannot.
        if stopped.is_none() {
            let mut tries = vec![model::flatten(&best_input)];
            while let Some(input) = tries.pop() {
                if iters >= 2 * MAX_SHRINK_ITERS {
                    break;
                }
                iters += 1;
                let tried = build(case, &input).and_then(|s| play(&s).map(|r| (s, r)));
                let (s, r) = match tried {
                    Ok(t) => t,
                    Err(e) => {
                        stopped = Some(e);
                        break;
                    }
                };
                if r.passed || failure_class(&r) != class {
                    continue;
                }
                best = (s, r);
                tries.clear();
                for i in 0..input.ops.len() {
                    let mut fewer = input.clone();
                    fewer.ops.remove(i);
                    tries.push(fewer);
                }
                if input.others > 0 {
                    tries.push(CaseInput { others: 0, ..input });
                }
            }
        }
        let (s, r) = best;
        // Written even when shrinking stopped on an error: the case failed.
        let out = write_failure(opts, &s)?;
        eprintln!(
            "aether-conform: generated case {case} of seed {} failed; shrunk to a case of {} \
             step(s) in {iters} tries and written to {} (replay with run --scenarios {})",
            opts.seed,
            s.steps.len(),
            out.display(),
            opts.failures.display()
        );
        if let Some(e) = stopped {
            return Err(e);
        }
        return Ok(ScenarioResult {
            name: "generated".into(),
            file: out,
            passed: false,
            steps: r.steps,
            error: r.error.map(|e| format!("case {case}: {e}")),
            skipped: None,
        });
    }
    Ok(ScenarioResult {
        name: "generated".into(),
        file: PathBuf::from(format!("{} cases, seed {}", opts.cases, opts.seed)),
        passed: true,
        steps: Vec::new(),
        error: None,
        skipped: None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::run::StepResult;

    fn result(steps: &[(serde_json::Value, bool)], error: Option<&str>) -> ScenarioResult {
        ScenarioResult {
            name: "c".into(),
            file: PathBuf::new(),
            passed: false,
            steps: steps
                .iter()
                .enumerate()
                .map(|(index, (request, passed))| StepResult {
                    index,
                    request: request.clone(),
                    expected: String::new(),
                    got: String::new(),
                    passed: *passed,
                    note: None,
                    answer: None,
                })
                .collect(),
            error: error.map(str::to_string),
            skipped: None,
        }
    }

    /// A shrinking candidate counts only if it fails the way the case did:
    /// a mismatch at a step of the same kind, or the same kind of error.
    #[test]
    fn a_failure_is_classed_by_its_first_failing_step() {
        use serde_json::json;
        let a = result(
            &[
                (json!({"op": "heartbeat"}), true),
                (json!({"op": "getattr", "root": 0, "path": "a"}), false),
            ],
            None,
        );
        let b = result(
            &[(json!({"op": "getattr", "root": 7, "path": "b"}), false)],
            None,
        );
        let c = result(
            &[(json!({"op": "readdir", "root": 0, "path": "."}), false)],
            None,
        );
        let d = result(
            &[(json!({"op": "heartbeat"}), true)],
            Some("mount refused: no"),
        );
        assert_eq!(failure_class(&a), failure_class(&b));
        assert_ne!(failure_class(&a), failure_class(&c));
        assert_ne!(failure_class(&a), failure_class(&d));
        assert_eq!(failure_class(&a).as_deref(), Some("mismatch at getattr"));
        assert_eq!(failure_class(&d).as_deref(), Some("error: mount refused"));
    }
}
